CREATE SCHEMA IF NOT EXISTS eventease;
REVOKE ALL ON SCHEMA eventease FROM PUBLIC;
CREATE TABLE IF NOT EXISTS eventease.events (
  id TEXT PRIMARY KEY, title TEXT NOT NULL, description TEXT NOT NULL,
  category TEXT NOT NULL, city TEXT NOT NULL, venue TEXT NOT NULL,
  date TEXT NOT NULL, organizer TEXT NOT NULL,
  price INTEGER NOT NULL CHECK (price BETWEEN 0 AND 1000000),
  capacity INTEGER NOT NULL CHECK (capacity BETWEEN 1 AND 100000),
  image TEXT NOT NULL, popularity INTEGER NOT NULL DEFAULT 0,
  duration TEXT NOT NULL DEFAULT '3 hours',
  highlights JSONB NOT NULL DEFAULT '[]', schedule JSONB NOT NULL DEFAULT '[]',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS eventease.registrations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id TEXT NOT NULL REFERENCES eventease.events(id),
  full_name TEXT NOT NULL, email TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(event_id, email)
);
CREATE TABLE IF NOT EXISTS eventease.bookings (
  id TEXT PRIMARY KEY, event_id TEXT NOT NULL REFERENCES eventease.events(id),
  name TEXT NOT NULL, email TEXT NOT NULL, phone TEXT NOT NULL, payment TEXT NOT NULL,
  subtotal INTEGER NOT NULL CHECK (subtotal >= 0), fee INTEGER NOT NULL CHECK (fee >= 0),
  total INTEGER NOT NULL CHECK (total = subtotal + fee), created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS eventease.booking_items (
  booking_id TEXT NOT NULL REFERENCES eventease.bookings(id),
  type TEXT NOT NULL CHECK (type IN ('early','general','vip')),
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 10),
  price INTEGER NOT NULL CHECK (price >= 0), PRIMARY KEY(booking_id,type)
);
CREATE INDEX IF NOT EXISTS idx_booking_event ON eventease.bookings(event_id);
CREATE INDEX IF NOT EXISTS idx_registration_event ON eventease.registrations(event_id);
REVOKE ALL ON ALL TABLES IN SCHEMA eventease FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA eventease FROM PUBLIC;
